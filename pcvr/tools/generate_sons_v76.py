def soft_bip(f0: float, f1: float, dur: float) -> np.ndarray:
    """Un bip d'hologramme : un son pur, chatoyant (deux voix désaccordées), qui glisse, très doux."""
    x = _t(dur)
    f = f0 * (f1 / f0) ** np.clip(x / max(dur * 0.7, 1e-3), 0, 1)
    ph = 2 * np.pi * np.cumsum(f) / SR
    ph2 = 2 * np.pi * np.cumsum(f * 1.004) / SR
    y = np.sin(ph) + 0.6 * np.sin(ph2) + 0.12 * np.sin(2 * ph)
    return y * np.clip(x / 0.004, 0, 1) * np.exp(-x / (dur * 0.6)) * np.clip((dur - x) / 0.01, 0, 1)


