def fontaine_holo(k: int) -> np.ndarray:
    """La fontaine holographique : l'eau lumineuse qui retombe dans la vasque, et les planètes qui
    chantent tout bas (des sons purs qui ondulent). Boucle de 4 s : tout est périodique."""
    dur = 4.0
    n = int(dur * SR)
    x = np.arange(n) / SR
    w = amb.loopify(s71.fontaine(n + SR).mean(axis=1), 1.0)[:n]           # (longueur : exactement n)
    splash = cfilt(nz(n), 1500, 7000) * (0.7 + 0.3 * np.sin(2 * np.pi * per(3.0, dur) * x))
    song = np.zeros(n)
    for f, cyc, ph in ((per(523.25, dur), 1, 0.0), (per(659.3, dur), 2, 1.3), (per(783.99, dur), 1, 2.6), (per(1046.5, dur), 3, 0.7)):
        song += np.sin(2 * np.pi * f * x) * (0.5 + 0.5 * np.sin(2 * np.pi * cyc * x / dur + ph)) ** 2
    y = unit(w) * 0.7 + unit(splash) * 0.15 + unit(song) * 0.12
    return loop_end(y)


