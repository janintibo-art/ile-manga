def teleporteur(k: int) -> np.ndarray:
    """Le téléporteur des Lumens : la charge (un son qui monte en tournant), la gerbe de cristaux,
    « fwoump » (le souffle aspiré, une note grave qui tombe), et le scintillement qui reste."""
    dur = 2.6
    x = _t(1.1)
    f = np.interp(x, [0, 1.1], [220.0, [1320.0, 1760.0][k]])
    ph = 2 * np.pi * np.cumsum(f) / SR
    charge = (np.sin(ph) + 0.4 * np.sin(2 * ph + np.sin(2 * np.pi * 14 * x))) * (x / 1.1) ** 1.5
    whoop = s63.whoosh(0.5, 6000.0, 300.0, 0.5)
    drop = hum(0.6, [180.0, 55.0], ((1, 1.0), (2, 0.3))) * np.exp(-_t(0.6) / 0.2)
    notes = [[79, 83, 86, 88, 91, 95, 98], [77, 81, 84, 88, 89, 93, 96]][k]
    parts = [(unit(charge), 0.0, 0.45), (unit(crystal_run(notes, 0.035, 1.2, 0.45, 0.4)), 0.95, 0.5),
             (unit(whoop), 1.05, 0.45), (unit(drop), 1.12, 0.5),
             (unit(etincelles(1.3, 30, 3500, 9500, (0.05, 0.2))), 1.15, 0.3)]
    out = mix(dur, *parts)
    return finish(room(out, 1.4, 3.5, 9000.0, 0.25, seed=7651 + k), 0.89, 0.5)


