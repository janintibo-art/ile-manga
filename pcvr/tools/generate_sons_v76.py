def saucer_pass(dur: float = 7.0, far: float = 1.0) -> np.ndarray:
    """Une soucoupe qui passe (stéréo) : le bourdon et le « wou-wou », l'effet Doppler, d'une oreille à l'autre."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    u = x / dur
    dop = 1 + 0.06 * np.tanh((0.5 - u) * 6)
    hm = hum(dur, 100.0 * dop, ((1, 1.0), (2, 0.5), (3, 0.3))) + 0.5 * np.sin(2 * np.pi * np.cumsum(560.0 * dop * (1 + 0.02 * np.sin(2 * np.pi * 2.2 * x))) / SR)
    env = np.exp(-((u - 0.5) / 0.22) ** 2)
    y = lp(hm, 2500 * far) * env
    p = np.clip((u - 0.5) * 2.2, -1, 1)
    return np.stack([y * np.sqrt(0.5 * (1 - p)), y * np.sqrt(0.5 * (1 + p))], axis=1)


def theremin_far(seed: int) -> np.ndarray:
    """Vibrato qui joue du thérémine sur l'Agora (entendu de loin) : une phrase lente, glissée."""
    rng = np.random.default_rng(seed)
    phrase = [(69, 1.6), (73, 0.8), (76, 2.0), (74, 0.8), (73, 0.8), (71, 2.4), (None, 0.8), (68, 1.2), (71, 1.2), (69, 3.0)]
    n = int(sum(d for _, d in phrase) * SR + SR)
    semis = np.zeros(n)
    amp = np.zeros(n)
    t = 0
    last = 69
    for m, d in phrase:
        k = int(d * SR)
        semis[t:t + k] = last if m is None else m
        amp[t:t + k] = 0.0 if m is None else 1.0
        last = last if m is None else m
        t += k
    semis[t:] = last
    from scipy import signal as sg
    a = np.exp(-1.0 / (0.1 * SR))
    semis = sg.lfilter([1 - a], [1, -a], semis, zi=[semis[0] * a])[0]
    amp = sg.lfilter([1 - np.exp(-1 / (0.12 * SR))], [1, -np.exp(-1 / (0.12 * SR))], amp)
    x = np.arange(n) / SR
    f = s75.m75.hz(semis + 0.25 * np.sin(2 * np.pi * 5.6 * x + rng.uniform(0, 6)))
    ph = 2 * np.pi * np.cumsum(f) / SR
    y = (np.sin(ph) + 0.15 * np.sin(2 * ph)) * amp
    return lp(y, 2500)


