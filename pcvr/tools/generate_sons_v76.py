def soucoupe_vol(k: int) -> np.ndarray:
    """Une soucoupe en vol : le bourdon (fondamentale et harmoniques), le « wou-wou » qui ondule, un
    sifflement aigu, l'air. Boucle de 2 s : toutes les fréquences font un nombre entier de tours."""
    dur = 2.0
    n = int(dur * SR)
