def rayon(k: int, up: bool) -> np.ndarray:
    dur = [3.4, 3.0][k]
    x = _t(dur)
    sweep = np.interp(x, [0, dur], [0.0, 1.0] if up else [1.0, 0.0])
    f0 = [110.0, 130.8][k]
    beam = hum(dur, f0 * 2 ** sweep, ((1, 1.0), (2, 0.6), (3, 0.35), (5, 0.15)))
    beam *= 1 + 0.25 * np.sin(2 * np.pi * (6 + 6 * sweep) * x)            # le faisceau qui palpite
    beam *= np.sin(np.pi * np.clip(x / dur, 0, 1)) ** 0.7
    air = s63.whoosh(dur, 400.0 if up else 4000.0, 4000.0 if up else 400.0, 0.4)
    scale = [62, 66, 69, 71, 74, 78, 81, 83, 86, 90] if k == 0 else [64, 67, 71, 72, 76, 79, 83, 84, 88, 91]
    notes = scale if up else scale[::-1]
    run = crystal_run(notes, (dur - 1.2) / len(notes), dur, 0.45, 0.35)
    last = [scale[-1], scale[-3], scale[-5]] if up else [scale[0], scale[2], scale[4]]
    parts = [(unit(beam), 0.0, 0.45), (unit(air), 0.0, 0.3), (unit(run), 0.15, 0.55),
             (unit(etincelles(dur * 0.8, 24, 3500, 9000, (0.05, 0.2))), 0.2, 0.25)]
    for j, m in enumerate(last):
        parts.append((unit(celesta(m + (0 if up else 12), 1.2, 0.5)), dur - 0.9 + j * 0.04, 0.35))
    if not up:      # on se pose : un « pouf » doux
        parts.append((unit(lp(bouffee(0.4, 80, 800, 0.01), 900)), dur - 0.5, 0.4))
    out = mix(dur + 1.0, *parts)
    return finish(room(out, 1.4, 3.5, 8000.0, 0.25, seed=7601 + k + (0 if up else 10)), 0.89, 0.5)


