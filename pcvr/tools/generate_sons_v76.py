def main() -> int:
    global VSCO, VCSL, DL
    if len(sys.argv) > 1 and Path(sys.argv[1]).is_dir():
        s63.LIB = Path(sys.argv[1])
        names = sys.argv[2:]
    else:
        names = sys.argv[1:]
    VSCO = s63.LIB.parent / "VSCO-2-CE"
    VCSL = s63.LIB.parent / "VCSL"
    DL = s63.LIB.parent / "dl"
    s75.VSCO, s75.VCSL, s75.DL = VSCO, VCSL, DL
    s70.VSCO, s70.VCSL = VSCO, VCSL
    s71.VSCO, s71.VCSL, s71.DL = VSCO, VCSL, DL
    m75.VSCO, m75.VCSL, m75.CC0 = VSCO, VCSL, s63.LIB
    for name, (fn, count, first, gain_db) in SOUNDS.items():
        if names and name not in names:
            continue
        xs = []
        for k in range(count):
            reseed(name, k)
            xs.append(np.asarray(fn(k), float))
        ref = min(s70.loudness(x) for x in xs) + gain_db
        for k, x in enumerate(xs):
            y = x * 10 ** ((ref - s70.loudness(x)) / 20.0)
            if np.max(np.abs(y)) > 0.89:
                y = s68.soft_limit(y, 0.89) if name not in LOOPS else y * 0.89 / np.max(np.abs(y))
            if name not in LOOPS:                  # sans le silence de la fin (on garde 50 ms, fondu)
                on = np.nonzero(np.abs(y) > 10 ** (-66 / 20))[0]
                if len(on):
                    y = _fade(y[: min(len(y), on[-1] + int(0.05 * SR))], 0.0, 0.03)
            s75.save_sfx(f"{name}_{first + k}", y)
            pk = np.max(np.abs(s70.read_raw(fx.OUT / f"{name}_{first + k}.ogg")))
            if pk > 0.93:
                s75.save_sfx(f"{name}_{first + k}", y * 0.89 / pk)
        print(" ", name, ", ".join(f"{name}_{first + k}" for k in range(count)))
    for name, fn in BEDS.items():
        if names and name not in names:
            continue
        reseed(name)
        s75.save_bed(name, fn(s63.LIB))
    return 0


if __name__ == "__main__":
    sys.exit(main())
