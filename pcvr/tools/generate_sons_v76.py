def nz(n: int) -> np.ndarray:
    return RNG.standard_normal(n)


def cfilt(x: np.ndarray, lo: float = 0.0, hi: float = 0.0, order: int = 2) -> np.ndarray:
    """Filtre dans le domaine des fréquences, sur tout le son d'un coup : il est circulaire (la fin
    filtre le début), donc une boucle filtrée reste une boucle parfaite."""
    n = len(x)
    f = np.fft.rfftfreq(n, 1.0 / SR)
    g = np.ones_like(f)
    if hi > 0:
        g /= np.sqrt(1 + (f / hi) ** (2 * order))
    if lo > 0:
        g /= np.sqrt(1 + (lo / np.maximum(f, 1e-3)) ** (2 * order))
    return np.fft.irfft(np.fft.rfft(x, axis=0) * (g[:, None] if x.ndim == 2 else g), n, axis=0)


def per(f: float, dur: float) -> float:
    """La fréquence la plus proche qui fait un nombre entier de cycles dans la boucle."""
    return max(1.0, round(f * dur)) / dur


def celesta(m: float, dur: float = 0.5, vel: float = 0.5) -> np.ndarray:
    return np.asarray(m75.celesta(m, dur, vel, RNG), float)


def crystal_run(notes, step: float, dur: float, vel: float = 0.5, glk: float = 0.4) -> np.ndarray:
    """Des notes de cristal (célesta et glockenspiel) qui s'enchaînent."""
    out = np.zeros(int(dur * SR))
    for i, m in enumerate(notes):
        y = addp(celesta(m, 0.4, vel), glk * s75.glock(m + 12) if glk > 0 else np.zeros(1))
        at = int(i * step * SR)
        if at < len(out):
            amb.place(out, y[: len(out) - at], at, 1.0)
    return out


def hum(dur: float, f, harm=((1, 1.0), (2, 0.5), (3, 0.25)), chorus: float = 0.003) -> np.ndarray:
    """Un bourdon lumineux : quelques harmoniques, trois voix à peine désaccordées (ça chatoie)."""
    x = _t(dur)
    fp = np.asarray(f, float)
    ff = np.interp(x, np.linspace(0, dur, len(fp)), fp) if fp.ndim and len(fp) > 1 else np.full(len(x), float(np.atleast_1d(fp)[0]))
    y = np.zeros(len(x))
    for d in (-chorus, 0.0, chorus):
        ph = 2 * np.pi * np.cumsum(ff * (1 + d)) / SR + RNG.uniform(0, 6)
        for k, a in harm:
            y += a * np.sin(k * ph)
    return y / 3


_INS = {}


def vnote(key: str, midi: float, dur: float, vel: float = 0.6) -> np.ndarray:
    """Une note d'un pupitre de VSCO-2 CE (compose_musique_v51) ou de la VCSL (compose_musique_v70), mono."""
    if key not in _INS:
        try:
            if key == "verres":
                import compose_musique_v70 as cm70
                cm70.VCSL = VCSL
                _INS[key] = cm70.vcsl("verres")
            else:
                import compose_musique_v51 as cm51
                cm51.VSCO = VSCO
                _INS[key] = cm51.I(key)
        except (FileNotFoundError, ValueError, KeyError):
            _INS[key] = None
    ins = _INS[key]
    if ins is None:
        return celesta(midi, dur, vel)
    return np.asarray(ins.note(midi, dur, vel), float).mean(axis=1)


def fanfare(seq, dur: float) -> np.ndarray:
    """Une petite fanfare : (instrument, note, instant, durée, force)."""
    out = np.zeros(int(dur * SR))
    for key, m, t, d, v in seq:
        y = vnote(key, m, d, v)
        at = int(t * SR)
        if at < len(out):
            amb.place(out, y[: len(out) - at], at, 1.0)
    return out


def loop_end(x: np.ndarray) -> np.ndarray:
    """Pour une boucle : coupe l'infra-grave (filtre circulaire) et normalise, sans fondu."""
    y = cfilt(x - np.mean(x), lo=35.0)
    return y / (np.max(np.abs(y)) + 1e-9) * 0.89


