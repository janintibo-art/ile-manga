def chantier_naval_bed(lib: Path, seconds: float = 60.0) -> np.ndarray:
    n = int(seconds * SR)

    def bed(m):
        water = s56.lapping(m) * 1.4
        swell = lp(amb.noise(m, "brown"), 250) * amb.smooth_env(m, 0.15, 0.3, 1.0) * 0.35
        return water + amb.stereo(swell, np.roll(swell, SR)) + s71.brise(m) * 0.1

    cont = loop_layer(bed, seconds, 3.0)
    surf = amb.surf(seconds + 3.0)[:n]            # (amb.surf rend déjà une boucle : seconds + 3 - 3 secondes)
    cont = cont + surf * 0.3
    work = np.zeros((n, 2))
    for at in (2.0, 9.5, 17.0, 26.0, 33.5, 44.0, 51.0):
        wplace(work, s68.hammering(), at * SR, RNG.uniform(0.12, 0.2), RNG.uniform(-0.8, 0.8))
    for at in (5.0, 29.0, 47.0):
        wplace(work, scie(int(RNG.integers(0, 3))), at * SR, 0.1, RNG.uniform(-0.6, 0.6))
    for at in (14.0, 40.0):
        wplace(work, marteau_chantier(int(RNG.integers(0, 3))), at * SR, 0.1, RNG.uniform(-0.5, 0.5))
    s68.voice_walla(lib, work, 3.0, 2000.0, (-4.0, 1.0), (0.04, 0.12))
    scatter(work, [unit(s68.rope_creak(RNG.uniform(1.0, 2.0))) for _ in range(3)], 5, (0.03, 0.07))
    scatter(work, [s61.chain() for _ in range(2)], 3, (0.04, 0.08), lp_hz=6000.0)
    work = room_wrap(work, 1.2, 3.0, 5000.0, 0.22, seed=7941)
    ev = np.zeros((n, 2))
    scatter(ev, [amb.gull(int(RNG.integers(0, 3))) for _ in range(5)], 9, (0.05, 0.12))
    scatter(ev, [unit(s56.halyard(k)) for k in range(3)], 5, (0.02, 0.05))
    ev = room_wrap(ev, 2.0, 2.0, 6000.0, 0.3, seed=7942)
    return finish_bed(cont + work + ev, 0.5)


