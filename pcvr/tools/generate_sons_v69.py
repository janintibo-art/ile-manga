def clay_flute(phrase, breath: float = 0.16) -> np.ndarray:
    """Une flûte d'argile : un son presque pur, beaucoup de souffle, des attaques « tu », une hauteur
    un peu instable. phrase = [(fréquence de départ, d'arrivée, durée, vibrato)], f = 0 : silence."""
    fs, amps, onsets = [], [], []
    pos = 0
    last = phrase[0][0]
    for fa, fb, d, vib in phrase:
        n = int(d * SR)
        x = np.arange(n) / SR
        if fa <= 0:
            fs.append(np.full(n, last))
            amps.append(np.zeros(n))
        else:
            f = np.interp(x, [0, min(0.05, d / 3), d], [fa * 0.96, fa, fb])
            f = f * (1 + vib * np.sin(2 * np.pi * 5.5 * x) * np.clip((x - 0.15) / 0.3, 0, 1))
            fs.append(f)
            amps.append(np.clip(x / 0.02, 0, 1) * np.clip((d - x) / 0.04, 0, 1) * np.interp(x, [0, d], [0.85, 1.0]))
            onsets.append(pos)
            last = fb
        pos += n
    f = np.concatenate(fs) * (1 + 0.004 * amb.smooth_env(pos, 8.0, -1, 1))
    a = np.concatenate(amps) * (1 + 0.04 * amb.smooth_env(pos, 12.0, -1, 1))
    ph = 2 * np.pi * np.cumsum(f) / SR
    y = (np.sin(ph) + 0.08 * np.sin(2 * ph) + 0.04 * np.sin(3 * ph)) * a
    y += amb.bp(RNG.standard_normal(pos), 1200, 5000) * a * breath
    for o in onsets:
        m = int(0.025 * SR)
        amb.place(y, amb.bp(RNG.standard_normal(m), 2000, 6000) * np.hanning(m) * 0.25, o, 1.0)
    return y


