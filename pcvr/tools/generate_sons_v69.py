def soleils_bed(lib: Path, seconds: float = 60.0) -> np.ndarray:
    n = int(seconds * SR)

    def fire(m):
        roar = amb.hp(amb.lp(amb.noise(m, "brown"), 300), 50) * 0.25 * amb.smooth_env(m, 1.2, 0.6, 1.0)
        breath = amb.bp(amb.noise(m, "pink"), 200, 1400) * 0.3 * amb.smooth_env(m, 0.8, 0.4, 1.0)
        cr = np.zeros(m)
        for _ in range(int(m / SR * 9)):
            k = int(RNG.uniform(0.002, 0.01) * SR)
            amb.place(cr, amb.hp(RNG.standard_normal(k), RNG.uniform(1200, 3000)) * np.exp(-np.arange(k) / (k / 3)),
                      int(RNG.integers(0, m - k)), RNG.uniform(0.1, 0.6) ** 2)
        cr = lp(cr, 3500) * 1.2
        g = amb.smooth_env(m, 0.1, 0.2, 1.0) ** 1.5
        wind = amb.bp(amb.noise(m, "pink"), 100, 900) * (0.3 + g) * 0.15
        return amb.stereo(roar + breath + cr + wind, np.roll(roar, SR // 3) + np.roll(breath, SR // 2) + np.roll(cr, SR // 5) + np.roll(wind, SR))

    cont = loop_layer(fire, seconds, 3.0)
    ev = np.zeros((n, 2))
    # le tambour lent, comme un cœur : « boum-boum » toutes les 2,5 s (24 par tour de boucle)
    drum = np.zeros((n, 2))
    period = 2.5
    for i in range(int(round(seconds / period))):
        b = addp(unit(membrane(RNG.uniform(60, 64), 1.4, 0.3, 0.35, 0.2)), np.zeros(1))
        b2 = unit(membrane(RNG.uniform(60, 64), 1.2, 0.25, 0.3, 0.15)) * 0.6
        wplace(drum, lp(b, 900), (i * period + 0.3) * SR, 0.22, 0.1)
        wplace(drum, lp(b2, 900), (i * period + 0.68) * SR, 0.22, 0.1)
    ev += room_wrap(drum, 2.5, 1.3, 1500.0, 0.5, seed=6940)
    scatter(ev, [amb.drip(k) for k in range(4)], 14, (0.05, 0.12))
    flares = []
    for _ in range(3):
        d = RNG.uniform(1.2, 2.2)
        x = _t(d)
        flares.append(unit(amb.bp(noise(d), 250, 2500) * np.sin(np.pi * x / d) ** 1.5))
    scatter(ev, flares, 2, (0.08, 0.14))
    ev = room_wrap(ev, 2.2, 1.6, 2500.0, 0.3, seed=6941)
    return finish_bed(cont + ev, 0.6)


