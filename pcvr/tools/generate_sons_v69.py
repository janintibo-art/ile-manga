def paddle_stroke() -> np.ndarray:
    """Un coup de pagaie : la pale qui entre dans l'eau, le remous, l'eau qui s'égoutte de la pale."""
    s = lp(clip_rec(SPL + "splash_%02d.ogg" % [8, 9, 13][RNG.integers(0, 3)], RNG.uniform(-5.0, -2.0), 0.4, 0.15), 2500)
    m = int(0.5 * SR)
    sw = amb.bp(RNG.standard_normal(m), 300, 1500) * np.sin(np.pi * np.arange(m) / m) * 0.3
    out = mix(1.4, (s, 0.0, 1.0), (unit(sw), 0.08, 0.35))
    for i in range(RNG.integers(2, 5)):
        amb.place(out, s59.drip(), int((0.6 + i * RNG.uniform(0.08, 0.15)) * SR), 0.08)
    if RNG.random() < 0.3:
        amb.place(out, clack(RNG.uniform(600, 900), 0.02, 0.5, 0.4), int(0.55 * SR), 0.25)
    return out


def canoe_pass(buf: np.ndarray, at: float, strokes: int = 7, gain: float = 0.3) -> None:
    for i in range(strokes):
        pan = -0.8 + 1.6 * i / max(1, strokes - 1)
        g = gain * np.sin(np.pi * (i + 0.5) / strokes) ** 0.6
        wplace(buf, paddle_stroke(), (at + i * 1.6 + RNG.uniform(-0.05, 0.05)) * SR, g, pan + (0.15 if i % 2 else -0.15))


def city_music(seconds: float = 12.0) -> np.ndarray:
    """La ville au loin : le huehuetl sur la grande place, une flûte d'argile qui joue un air."""
    out = np.zeros(int((seconds + 1.0) * SR))
    spb = 60.0 / 100.0
    b = 0.0
    while b * spb < seconds:
        for off, op, v in ((0, True, 1.0), (1.5, True, 0.7), (2, False, 0.5), (3, True, 0.8)):
            if (b + off) * spb >= seconds:
                continue
            amb.place(out, unit(membrane(72.0 if op else 140.0, 1.0, 0.28 if op else 0.12, 0.4, 0.3)) * v,
                      int((b + off) * spb * SR), 0.6)
        b += 4
    notes = [(1175, 1175, 0.3, 0.0), (1320, 1320, 0.3, 0.0), (1568, 1568, 0.6, 0.006), (1320, 1320, 0.3, 0.0),
             (1175, 1175, 0.3, 0.0), (990, 990, 0.9, 0.006), (0, 0, 0.6, 0.0), (1175, 1175, 0.3, 0.0),
             (1320, 1320, 0.3, 0.0), (1175, 1175, 0.3, 0.0), (990, 990, 0.3, 0.0), (880, 880, 1.2, 0.006)]
    amb.place(out, unit(clay_flute(notes)) * 0.5, int(2.4 * SR), 1.0)
    return out


