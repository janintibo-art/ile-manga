def echoes(x: np.ndarray, taps, lp_hz: float = 2500.0) -> np.ndarray:
    """Des échos nets (murs d'un terrain de balle, vallée) : (retard s, gain)."""
    out = np.concatenate([x, np.zeros(int(max(d for d, _ in taps) * SR) + 10)])
    y = lp(x, lp_hz)
    for d, g in taps:
        k = int(d * SR)
        out[k:k + len(y)] += y * g
    return out


