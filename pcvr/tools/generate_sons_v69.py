def main() -> int:
    global VSCO, DNAABR
    if len(sys.argv) > 1 and Path(sys.argv[1]).is_dir():
        s63.LIB = Path(sys.argv[1])
        VSCO = s63.LIB.parent / "VSCO-2-CE"
        DNAABR = s63.LIB.parent / "dl"
        names = sys.argv[2:]
    else:
        names = sys.argv[1:]
    for name, (fn, count) in SOUNDS.items():
        if names and name not in names:
            continue
        xs = []
        for k in range(count):
            reseed(name, k)
            xs.append(fn(k))
        # les variantes d'une même famille sont mises à la même sonie (la plus douce)
        ref = min(s68.loudness(x) for x in xs)
        for k, x in enumerate(xs):
            fx.save(f"{name}_{k + 1}", x * 10 ** ((ref - s68.loudness(x)) / 20.0))
        print(" ", name, count)
    for name, fn in BEDS.items():
        if names and name not in names:
            continue
        reseed(name)
        amb.save(f"ambiance/{name}", fn(s63.LIB))
    return 0


