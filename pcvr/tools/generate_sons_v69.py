def denoise(x: np.ndarray, over: float = 2.0, quiet: float = 12.0, nper: int = 1024) -> np.ndarray:
    """Débruitage spectral : le profil du bruit est pris sur les trames les plus calmes, puis
    retranché (gain lissé dans le temps et en fréquence, sans « gazouillis »)."""
    f, t, z = signal.stft(x, SR, nperseg=nper)
    mag = np.abs(z)
    e = mag.sum(axis=0)
    calm = e <= np.percentile(e, quiet)
    prof = mag[:, calm].mean(axis=1, keepdims=True) if calm.any() else np.percentile(mag, 10, axis=1, keepdims=True)
    g = np.clip(1.0 - over * prof / (mag + 1e-12), 0.0, 1.0)
    g = ndimage.uniform_filter(g, size=(3, 5))
    _, y = signal.istft(z * g, SR, nperseg=nper)
    return y[: len(x)]


def glide_slow(x: np.ndarray, r0: float, r1: float) -> np.ndarray:
    """Ralentit un son de plus en plus (r0 au début, r1 à la fin) : il grave en descendant."""
    m = int(len(x) * (r0 + r1) / 2) + 2
    rate = 1.0 / np.linspace(r0, r1, m)
    p = np.cumsum(rate) - rate[0]
    p = p[p < len(x) - 1]
    return np.interp(p, np.arange(len(x)), x)


def vowel_track(n: int, seq, scale: float = 1.0, bw: float = 1.0):
    """Trois formants qui glissent d'une voyelle à l'autre : seq = [(instant 0..1, voyelle), ...]."""
    u = np.arange(n) / max(1, n - 1)
    ts = [a for a, _ in seq]
    out = []
    for i in range(3):
        F = np.interp(u, ts, [VOW[v][i][0] * scale for _, v in seq])
        out.append((F, VOW[seq[0][1]][i][1] * scale * bw, VOW[seq[0][1]][i][2]))
    return out


def voice(dur: float, f0, fmts, tp=None, tilt: float = 1.0, fmax: float = 5000.0, breath: float = 0.3,
          rasp: float = 0.0, sub: float = 0.0, sat: float = 0.0, jitter: float = 0.01, att: float = 0.05,
          rel: float = 0.2, breath_lo: float = 300.0) -> np.ndarray:
    """Une voix de bête : source voisée (hauteur f0 qui suit un contour), raucité (hauteur qui
    grésille), sous-harmonique (voix « double » des grands animaux), souffle, formants, saturation."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    fp = np.atleast_1d(np.asarray(f0, float))
    tpp = np.linspace(0, dur, len(fp)) if tp is None else np.asarray(tp, float) * dur
    f = np.interp(x, tpp, fp) if len(fp) > 1 else np.full(n, fp[0])
    if rasp > 0:
        fm = amb.bp(RNG.standard_normal(n), 25.0, 250.0)
        f = f * (1 + rasp * fm / (np.std(fm) + 1e-9))
    f = np.clip(f, 0.5 * float(np.min(fp)), None)
    src = s68.glottal(f, tilt=tilt, fmax=fmax, jitter=jitter)
    src = src / (np.std(src) + 1e-9)
    if sub > 0:
        ph = 2 * np.pi * np.cumsum(f) / SR
        src = src + sub * np.sin(0.5 * ph) * (1 + np.sin(ph))
    if breath > 0:
        src = src + amb.hp(RNG.standard_normal(n), breath_lo) * breath
    y = formants(src, fmts)
    if sat > 0:
        y = np.tanh(sat * y / (np.max(np.abs(y)) + 1e-9))
    env = np.clip(x / max(att, 1e-3), 0, 1) * np.clip((dur - x) / max(rel, 1e-3), 0, 1) ** 1.3
    return y * env


def whisper(dur: float, seq, scale: float = 1.0, lo: float = 150.0, att: float = 0.12, rel: float = 0.6) -> np.ndarray:
    """Un souffle qui forme des voyelles (soupir, expiration) : du bruit dans des formants."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    src = amb.bp(RNG.standard_normal(n), lo, 6000)
    y = formants(src, vowel_track(n, seq, scale, bw=1.6))
    return y * np.clip(x / att, 0, 1) * np.clip((dur - x) / rel, 0, 1) ** 1.5


def grains(dur: float, rate, lo: float, hi: float) -> np.ndarray:
    """Des grains (sable, gravier, écailles) : des impulsions au hasard, filtrées.
    rate : grains par seconde (nombre, ou fonction du temps)."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    r = rate(x) if callable(rate) else np.full(n, float(rate))
    imp = (RNG.random(n) < r / SR).astype(float) * RNG.uniform(0.2, 1.0, n)
    return amb.bp(imp, lo, hi)


def membrane(f: float, dur: float = 1.2, decay: float = 0.25, bright: float = 0.5, slap: float = 0.3) -> np.ndarray:
    """Une peau de tambour : les modes d'une membrane ronde (la hauteur qui retombe juste après le
    coup), et la claque de la main."""
    x = _t(dur)
    fi = f * (1 + 0.18 * np.exp(-x / 0.04))
    ph = 2 * np.pi * np.cumsum(fi) / SR
    y = np.zeros(len(x))
    for r, a, d in [(1.0, 1.0, 1.0), (1.59, 0.45, 0.55), (2.14, 0.3, 0.4), (2.30, 0.25, 0.35), (2.65, 0.18, 0.3), (2.92, 0.12, 0.25)]:
        y += a * (bright if r > 1 else 1.0) * np.sin(r * ph + RNG.uniform(0, 6)) * np.exp(-x / (decay * d))
    m = int(0.03 * SR)
    y[:m] += amb.bp(RNG.standard_normal(m), 300, 3000) * np.exp(-np.arange(m) / SR / 0.006) * slap * 2
    return y * np.clip(x / 0.002, 0, 1)


