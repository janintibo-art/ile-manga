def sand_trickle(dur: float) -> np.ndarray:
    """Du sable qui coule d'une fente : un ruissellement de grains qui enfle puis s'épuise."""
    env = lambda tt: 1800 * np.sin(np.pi * np.clip(tt / dur, 0, 1)) ** 0.7  # noqa: E731
    g = grains(dur, env, 2500, 9000)
    x = _t(dur)
    h = amb.bp(noise(dur), 3000, 9000) * np.sin(np.pi * np.clip(x / dur, 0, 1)) ** 0.7 * 0.15
    return g + h


