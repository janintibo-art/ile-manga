def squeak(f0: float, f1: float, dur: float, rough: float = 0.0) -> np.ndarray:
    """Un cri de chauve-souris : un sifflement très aigu qui glisse, un peu grinçant."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    f = np.interp(x, [0, dur * 0.25, dur], [f0 * 0.9, f0, f1])
    if rough:
        f = f * (1 + rough * np.sin(2 * np.pi * RNG.uniform(70, 110) * x))
    ph = 2 * np.pi * np.cumsum(f) / SR
    y = np.zeros(n)
    for k, a in ((1, 1.0), (2, 0.35), (3, 0.12)):
        if k * f.max() < 19000:
            y += a * np.sin(k * ph)
    y += amb.bp(RNG.standard_normal(n), 3000, 10000) * 0.15
    return y * np.sin(np.pi * np.clip(x / dur, 0, 1)) ** 0.6


def flutter(dur: float, rate: float = 14.0, lo: float = 500.0, hi: float = 4000.0) -> np.ndarray:
    """Des ailes de chauve-souris : des battements rapides, secs, froissés (le vol qui passe)."""
    out = np.zeros(int((dur + 0.1) * SR))
    t = 0.0
    m = int(0.05 * SR)
    xs = np.arange(m) / SR
    while t < dur:
        e = amb.bp(RNG.standard_normal(m), lo, hi) * np.exp(-xs / 0.012) * np.clip(xs / 0.003, 0, 1)
        e += amb.bp(RNG.standard_normal(m), 150, 600) * np.exp(-xs / 0.02) * 0.6
        amb.place(out, e, int(t * SR), np.sin(np.pi * t / dur) ** 0.5 * RNG.uniform(0.6, 1.0))
        t += 1.0 / rate * RNG.uniform(0.85, 1.15)
    return out


