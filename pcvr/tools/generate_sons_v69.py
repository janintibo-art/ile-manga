def purr(dur: float) -> np.ndarray:
    """Un ronronnement : des impulsions de gorge (≈ 25 par seconde) dans un souffle nasal,
    l'expiration plus forte que l'inspiration."""
    n = int(dur * SR)
    x = np.arange(n) / SR
    cyc = 0.95
    ex = (np.floor(x / cyc) % 2) == 0
    rate = np.where(ex, 26.0, 22.5) * (1 + 0.03 * amb.smooth_env(n, 3.0, -1, 1))
    ph = np.cumsum(rate) / SR
    pulse = np.exp(-(ph % 1.0) * 7.0)
    exc = lp(RNG.standard_normal(n), 1400) * pulse + np.sin(2 * np.pi * ph) * 0.3 * pulse
    y = formants(exc, [(170, 90, 1.0), (460, 150, 0.6), (1150, 300, 0.2)])
    breath = np.abs(np.sin(np.pi * x / cyc)) ** 0.6 * np.where(ex, 1.0, 0.6)
    return y * breath * np.clip(x / 0.1, 0, 1) * np.clip((dur - x) / 0.3, 0, 1)


